// ===== 主流程 =====
function main() {
  // 1. 读取全部卦象文件，提取经文用字
  const files = fs.readdirSync(SRC_DIR)
    .filter(f => f.endsWith('.json'))
    .sort();

  const allChars = new Set();

  for (const file of files) {
    const data = JSON.parse(fs.readFileSync(path.join(SRC_DIR, file), 'utf-8'));
    // 提取五类经文文本
    const texts = [data.guaci, data.tuan, data.xiang];
    if (data.yaoci) {
      data.yaoci.forEach(y => {
        texts.push(y.text);
        texts.push(y.xiang);
      });
    }
    // 逐字提取汉字
    texts.filter(Boolean).forEach(t => {
      for (const ch of t) {
        if (/[一-鿿㐀-䶿]/.test(ch)) {
          allChars.add(ch);
        }
      }
    });
  }

  console.log(`Total unique characters in texts: ${allChars.size}`);

  // 2. 读取现有 annotations.json
  let annotations = { pinyin: {}, glossary: {} };
  if (fs.existsSync(ANNO_FILE)) {
    annotations = JSON.parse(fs.readFileSync(ANNO_FILE, 'utf-8'));
    if (!annotations.pinyin) annotations.pinyin = {};
  }

  const existingCount = Object.keys(annotations.pinyin).length;
  console.log(`Existing pinyin entries: ${existingCount}`);

  // 3. 合并拼音（不覆盖已有条目）
  let addedCount = 0;
  let missingChars = [];

  for (const ch of allChars) {
    // 已有条目跳过（保留人工校正值）
    if (annotations.pinyin[ch]) continue;

    if (PINYIN_DICT[ch]) {
      annotations.pinyin[ch] = PINYIN_DICT[ch];
      addedCount++;
    } else {
      missingChars.push(ch);
    }
  }

  // 4. 按 Unicode 码点排序 pinyin 字段，使 JSON 整洁
  const sortedPinyin = {};
  Object.keys(annotations.pinyin)
    .sort((a, b) => a.codePointAt(0) - b.codePointAt(0))
    .forEach(k => { sortedPinyin[k] = annotations.pinyin[k]; });
  annotations.pinyin = sortedPinyin;

  // 5. 写入文件
  fs.writeFileSync(ANNO_FILE, JSON.stringify(annotations, null, 2), 'utf-8');

  console.log(`Added ${addedCount} new pinyin entries`);
  console.log(`Total pinyin entries now: ${Object.keys(annotations.pinyin).length}`);

  if (missingChars.length > 0) {
    console.warn(`\nWARNING: ${missingChars.length} characters missing pinyin:`);
    console.warn(missingChars.join(' '));
  } else {
    console.log('\nAll characters have pinyin coverage!');
  }
}

main();
