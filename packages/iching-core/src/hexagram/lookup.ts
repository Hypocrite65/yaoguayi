/**
 * 根据六爻爻值查找卦序号
 * @param lines 六爻数组（由下至上）
 * @returns 卦序号（1-64），找不到返回 -1
 */
export function lookupHexagram(lines: LineValue[]): number {
  const key = lines.join('')
  return HEXAGRAM_INDEX[key] ?? -1
}
